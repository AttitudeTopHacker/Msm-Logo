#!/usr/bin/env python3
"""
MsmLogo Backend Privilege Escalation Helper.
Executed via pkexec with root privileges to apply Plymouth themes,
configure GRUB backgrounds, and update initramfs.
"""

import os
import sys
import shutil
import argparse
import subprocess
import json

BACKUP_FILE = "/etc/msmlogo_backup.json"
GRUB_CONFIG_FILE = "/etc/default/grub.d/99_msmlogo.cfg"


def log(msg: str, progress: int = -1):
    payload = {"message": msg}
    if progress >= 0:
        payload["progress"] = progress
    print(f"MSM_STATUS:{json.dumps(payload)}", flush=True)


def run_command(cmd_list, desc="Running system command"):
    log(f"{desc}: {' '.join(cmd_list)}")
    proc = subprocess.Popen(cmd_list, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    if proc.stdout:
        for line in proc.stdout:
            stripped = line.strip()
            if stripped:
                print(f"MSM_LOG:{stripped}", flush=True)
    proc.wait()
    if proc.returncode != 0:
        raise RuntimeError(f"Command failed with exit code {proc.returncode}: {' '.join(cmd_list)}")


def configure_reboot_safety():
    """Ensure plymouth-reboot does not block system shutdown/reboot by capping start timeout."""
    override_dir = "/etc/systemd/system/plymouth-reboot.service.d"
    override_file = os.path.join(override_dir, "timeout.conf")
    try:
        os.makedirs(override_dir, exist_ok=True)
        with open(override_file, "w", encoding="utf-8") as f:
            f.write("# Generated by MsmLogo to prevent shutdown/reboot delays\n[Service]\nTimeoutStartSec=10s\nTimeoutStopSec=5s\n")
        subprocess.run(["systemctl", "daemon-reload"], capture_output=True)
        log("Configured shutdown safety timeout (10s max).")
    except Exception as e:
        log(f"Notice setting reboot timeout: {e}")


def backup_original_theme():
    if not os.path.exists(BACKUP_FILE):
        try:
            # Query current default.plymouth
            res = subprocess.run(["update-alternatives", "--query", "default.plymouth"], capture_output=True, text=True)
            current_value = ""
            for line in res.stdout.splitlines():
                if line.startswith("Value:"):
                    current_value = line.split(":", 1)[1].strip()
                    break
            
            if not current_value or not os.path.exists(current_value):
                if os.path.exists("/usr/share/plymouth/themes/mint-logo/mint-logo.plymouth"):
                    current_value = "/usr/share/plymouth/themes/mint-logo/mint-logo.plymouth"
                elif os.path.exists("/usr/share/plymouth/themes/bgrt/bgrt.plymouth"):
                    current_value = "/usr/share/plymouth/themes/bgrt/bgrt.plymouth"

            data = {"original_theme": current_value}
            with open(BACKUP_FILE, "w", encoding="utf-8") as f:
                json.dump(data, f, indent=2)
            log(f"Backed up original boot theme: {current_value}")
        except Exception as e:
            log(f"Warning: Could not backup original theme: {e}")


def apply_theme(theme_src_dir: str, theme_name: str, sync_grub: bool = True):
    log(f"Starting theme installation for: {theme_name}", 5)
    
    if not os.path.isdir(theme_src_dir):
        raise FileNotFoundError(f"Source theme directory not found: {theme_src_dir}")

    # Ensure theme name has msm- prefix
    clean_name = theme_name.strip()
    if not clean_name.startswith("msm-"):
        clean_name = f"msm-{clean_name}"

    dest_dir = f"/usr/share/plymouth/themes/{clean_name}"
    plymouth_file = f"{dest_dir}/{clean_name}.plymouth"

    # Step 1: Backup current theme & configure reboot safety
    log("Checking and preserving system boot configuration backup...", 15)
    backup_original_theme()
    configure_reboot_safety()

    # Step 2: Copy theme files
    log(f"Installing theme assets to {dest_dir}...", 25)
    if os.path.exists(dest_dir):
        shutil.rmtree(dest_dir)
    shutil.copytree(theme_src_dir, dest_dir)
    os.chmod(dest_dir, 0o755)
    for root, dirs, files in os.walk(dest_dir):
        for f in files:
            os.chmod(os.path.join(root, f), 0o644)

    # Step 3: Register in update-alternatives
    log("Registering theme in Plymouth alternatives database...", 40)
    run_command([
        "update-alternatives", "--install",
        "/usr/share/plymouth/themes/default.plymouth",
        "default.plymouth",
        plymouth_file,
        "250"
    ], "Registering Plymouth theme alternative")

    # Step 4: Set as active
    log("Activating new theme as system default...", 55)
    run_command([
        "update-alternatives", "--set",
        "default.plymouth",
        plymouth_file
    ], "Setting default Plymouth theme")

    # Step 5: Configure GRUB if requested
    if sync_grub:
        grub_bg = f"{dest_dir}/grub-background.png"
        if os.path.exists(grub_bg) and os.path.exists("/usr/sbin/update-grub"):
            log("Configuring matching GRUB bootloader background...", 65)
            os.makedirs(os.path.dirname(GRUB_CONFIG_FILE), exist_ok=True)
            with open(GRUB_CONFIG_FILE, "w", encoding="utf-8") as f:
                f.write(f'# Generated by MsmLogo Boot Manager\nGRUB_BACKGROUND="{grub_bg}"\n')
            
            try:
                run_command(["update-grub"], "Updating GRUB configuration")
            except Exception as e:
                log(f"GRUB update warning: {e}")

    # Step 6: Update initramfs
    log("Generating initial RAM disk (update-initramfs -u)... This may take a minute.", 75)
    run_command(["update-initramfs", "-u"], "Updating initramfs")

    log("Boot theme applied successfully!", 100)


def switch_theme(plymouth_path: str, sync_grub: bool = False):
    log(f"Switching system boot theme to: {plymouth_path}", 10)
    if not os.path.exists(plymouth_path):
        raise FileNotFoundError(f"Theme file does not exist: {plymouth_path}")

    log("Setting active Plymouth theme...", 30)
    run_command(["update-alternatives", "--set", "default.plymouth", plymouth_path], "Switching theme")

    # If switching away from msm and grub config exists, remove custom grub config
    if os.path.exists(GRUB_CONFIG_FILE) and "msm-" not in plymouth_path:
        log("Resetting GRUB background configuration...", 50)
        try:
            os.remove(GRUB_CONFIG_FILE)
            if os.path.exists("/usr/sbin/update-grub"):
                run_command(["update-grub"], "Updating GRUB")
        except Exception as e:
            log(f"Warning: {e}")

    log("Rebuilding initramfs for switched theme...", 70)
    run_command(["update-initramfs", "-u"], "Updating initramfs")
    log("Theme switched successfully!", 100)


def find_official_default_theme() -> str:
    """Finds the system's official factory theme (e.g. mint-logo, bgrt, ubuntu-logo, etc.)."""
    # 1. Check backup file
    if os.path.exists(BACKUP_FILE):
        try:
            with open(BACKUP_FILE, "r", encoding="utf-8") as f:
                data = json.load(f)
            orig = data.get("original_theme")
            if orig and os.path.exists(orig) and "msm-" not in orig:
                return orig
        except Exception:
            pass

    # 2. Query system alternatives for official themes
    try:
        res = subprocess.run(["update-alternatives", "--display", "default.plymouth"], capture_output=True, text=True)
        for line in res.stdout.splitlines():
            line = line.strip()
            if line.startswith("/") and line.endswith(".plymouth") and "msm-" not in line:
                path = line.split()[0]
                if os.path.exists(path):
                    return path
    except Exception:
        pass

    # 3. Known standard distribution themes
    candidates = [
        "/usr/share/plymouth/themes/mint-logo/mint-logo.plymouth",
        "/usr/share/plymouth/themes/bgrt/bgrt.plymouth",
        "/usr/share/plymouth/themes/ubuntu-logo/ubuntu-logo.plymouth",
        "/usr/share/plymouth/themes/spinner/spinner.plymouth",
        "/usr/share/plymouth/themes/details/details.plymouth",
        "/usr/share/plymouth/themes/text/text.plymouth",
    ]
    for c in candidates:
        if os.path.exists(c):
            return c

    raise FileNotFoundError("Could not find any standard Linux default boot theme in /usr/share/plymouth/themes/")


def restore_backup():
    log("Restoring original factory boot theme...", 10)
    target_theme = find_official_default_theme()
    log(f"Identified official default theme: {target_theme}", 25)

    # Reset custom GRUB background if present
    if os.path.exists(GRUB_CONFIG_FILE):
        log("Resetting custom GRUB background...", 40)
        try:
            os.remove(GRUB_CONFIG_FILE)
            if os.path.exists("/usr/sbin/update-grub"):
                run_command(["update-grub"], "Updating GRUB configuration")
        except Exception as e:
            log(f"Notice: {e}")

    # Switch to the factory default theme
    switch_theme(target_theme, sync_grub=False)
    log("Official factory boot theme restored successfully!", 100)


def delete_theme(theme_name: str):
    clean_name = theme_name.strip()
    theme_dir = f"/usr/share/plymouth/themes/{clean_name}"
    plymouth_file = f"{theme_dir}/{clean_name}.plymouth"

    # Check if this theme is currently active
    curr_active = ""
    try:
        res = subprocess.run(["update-alternatives", "--query", "default.plymouth"], capture_output=True, text=True)
        for line in res.stdout.splitlines():
            if line.startswith("Value:"):
                curr_active = line.split(":", 1)[1].strip()
                break
    except Exception:
        pass

    # If the user is deleting the currently active theme, restore factory default first
    if curr_active and (curr_active == plymouth_file or clean_name in curr_active):
        log(f"Custom theme '{clean_name}' is currently active. Restoring Linux default logo first...", 20)
        restore_backup()

    log(f"Removing custom theme {clean_name}...", 60)
    if os.path.exists(plymouth_file):
        try:
            run_command(["update-alternatives", "--remove", "default.plymouth", plymouth_file], "Removing alternative")
        except Exception as e:
            log(f"Warning removing alternative: {e}")

    if os.path.exists(theme_dir):
        shutil.rmtree(theme_dir)
        log(f"Removed directory {theme_dir}")

    log(f"Theme {theme_name} deleted and default logo restored cleanly.", 100)


def main():
    parser = argparse.ArgumentParser(description="MsmLogo Backend Privilege Escalation Helper")
    parser.add_argument("--action", choices=["apply", "switch", "restore", "delete"], default="apply")
    parser.add_argument("--theme-dir", type=str, help="Path to staged theme directory")
    parser.add_argument("--theme-name", type=str, help="Theme name")
    parser.add_argument("--plymouth-path", type=str, help="Full path to .plymouth file")
    parser.add_argument("--sync-grub", action="store_true", help="Sync GRUB background")

    args = parser.parse_args()

    # Verify root
    if os.geteuid() != 0:
        print("ERROR: This helper must be executed with root privileges (e.g. via pkexec).", file=sys.stderr)
        sys.exit(1)

    try:
        if args.action == "apply":
            if not args.theme_dir or not args.theme_name:
                print("ERROR: --theme-dir and --theme-name are required for apply.", file=sys.stderr)
                sys.exit(1)
            apply_theme(args.theme_dir, args.theme_name, sync_grub=args.sync_grub)

        elif args.action == "switch":
            if not args.plymouth_path:
                print("ERROR: --plymouth-path is required for switch.", file=sys.stderr)
                sys.exit(1)
            switch_theme(args.plymouth_path, sync_grub=args.sync_grub)

        elif args.action == "restore":
            restore_backup()

        elif args.action == "delete":
            if not args.theme_name:
                print("ERROR: --theme-name is required for delete.", file=sys.stderr)
                sys.exit(1)
            delete_theme(args.theme_name)

    except Exception as e:
        log(f"FATAL ERROR: {str(e)}", -1)
        print(f"MSM_ERROR:{str(e)}", file=sys.stderr, flush=True)
        sys.exit(2)


if __name__ == "__main__":
    main()
